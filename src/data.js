// Оптическая сила (SPH): шаг 0.25 до ±6.00, дальше шаг 0.50
function sph(min = -12, max = 8, withZero = false) {
  const f = x => (x > 0 ? '+' : x < 0 ? '-' : '') + (Math.abs(x) / 100).toFixed(2);
  const step = x => (Math.abs(x) < 600 ? 25 : 50);
  const minus = [], plus = [];
  for (let x = -50; x >= min * 100; x -= step(x)) minus.push(f(x));
  for (let x = 50; x <= max * 100; x += step(x)) plus.push(f(x));
  const groups = [];
  if (withZero) groups.push({ label: 'Без диоптрий', values: ['0.00'] });
  if (minus.length) groups.push({ label: 'Минус (близорукость)', values: minus });
  if (plus.length) groups.push({ label: 'Плюс (дальнозоркость)', values: plus });
  return {
    k: 'sph', short: 'SPH', label: 'Оптическая сила (SPH)', groups,
    hint: 'Указана на упаковке ваших линз или в рецепте. Если глазам нужна разная сила, добавьте две упаковки с разными значениями.',
  };
}
