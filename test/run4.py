import asyncio, sys, urllib.parse
sys.path.insert(0, __import__('os').path.dirname(__import__('os').path.abspath(__file__)))
from run import setup, BASE, ROOT, decode, pick_branch
from playwright.async_api import async_playwright
F = 'optika-4-lupa.html'
SH = f'{ROOT}/shots'

async def overflow(page):
    return await page.evaluate("""[...document.querySelectorAll('.chart-row:not(.r6) b')].map(b => [b.textContent, b.scrollWidth - b.clientWidth, getComputedStyle(b).fontSize])""")

async def main(mode):
    async with async_playwright() as p:
        b = await p.chromium.launch(executable_path='/usr/bin/google-chrome', args=['--no-sandbox'])
        errs = []
        if mode in ('shots', 'all'):
            for lang in ('az', 'ru', 'en'):
                ctx = await b.new_context(viewport={'width': 1440, 'height': 900})
                pg = await ctx.new_page(); pg.on('pageerror', lambda e: errs.append(str(e)))
                await setup(pg)
                await pg.goto(f'{BASE}/dist/{F}?lang={lang}'); await pg.wait_for_timeout(1800)
                await pg.screenshot(path=f'{SH}/v4-{lang}-d-hero.png')
                await pg.locator('#eye').scroll_into_view_if_needed(); await pg.wait_for_timeout(2800)
                await pg.screenshot(path=f'{SH}/v4-{lang}-d-eye.png')
                print(lang, 'chart overflow:', await overflow(pg))
                await pg.evaluate('window.scrollTo(0,0)'); await pg.wait_for_timeout(300)
                await pg.screenshot(path=f'{SH}/v4-{lang}-d-full.png', full_page=True)
                await ctx.close()
                ctx = await b.new_context(viewport={'width': 390, 'height': 844}, device_scale_factor=2, is_mobile=True, has_touch=True)
                pg = await ctx.new_page(); pg.on('pageerror', lambda e: errs.append('m:' + str(e)))
                await setup(pg)
                await pg.goto(f'{BASE}/dist/{F}?lang={lang}'); await pg.wait_for_timeout(1800)
                await pg.screenshot(path=f'{SH}/v4-{lang}-m-hero.png')
                await pg.locator('#eye').scroll_into_view_if_needed(); await pg.wait_for_timeout(2800)
                await pg.screenshot(path=f'{SH}/v4-{lang}-m-eye.png')
                print(lang, 'mobile chart overflow:', await overflow(pg))
                await ctx.close()
        if mode in ('flow', 'all'):
            ctx = await b.new_context(viewport={'width': 1440, 'height': 900})
            pg = await ctx.new_page(); pg.on('pageerror', lambda e: errs.append(str(e)))
            pg.on('console', lambda m: errs.append('console ' + m.type + ': ' + m.text) if m.type == 'error' else None)
            await setup(pg)
            await pg.goto(f'{BASE}/dist/{F}'); await pg.wait_for_timeout(1500)
            print('html lang:', await pg.evaluate('document.documentElement.lang'), '| title:', await pg.title())
            await pg.locator('#productsGrid [data-pid="f-milan"] [data-add]').click(); await pg.wait_for_timeout(300)
            print('toast:', await pg.inner_text('#toastText'))
            await pg.locator('#catTabs [data-cat="contacts"]').click(); await pg.wait_for_timeout(200)
            await pg.locator('#productsGrid [data-pid="c-daily"] [data-add]').click(); await pg.wait_for_timeout(400)
            await pg.locator('#pmAdd').click(); await pg.wait_for_timeout(200)
            print('pm error:', await pg.inner_text('#pmError'))
            await pg.select_option('#opt-sph', '-2.50'); await pg.select_option('#opt-bc', '8.5')
            await pg.locator('[data-pm-qty="1"]').click(); await pg.wait_for_timeout(200)
            await pg.screenshot(path=f'{SH}/v4-az-d-product.png')
            await pg.locator('#pmAdd').click(); await pg.wait_for_timeout(400)
            await pg.locator('#catTabs [data-cat="lenses"]').click()
            await pg.locator('#productsGrid [data-pid="l-blue"] [data-add]').click(); await pg.wait_for_timeout(400)
            await pg.select_option('#opt-index', '1.60'); await pg.locator('#pmAdd').click(); await pg.wait_for_timeout(400)
            await pg.locator('.site-header [data-open-cart]').click(); await pg.wait_for_timeout(500)
            await pg.screenshot(path=f'{SH}/v4-az-d-cart.png')
            await pg.locator('#cartDrawer [data-checkout]').click(); await pg.wait_for_timeout(500)
            await pg.locator('#checkoutForm [type=submit]').click(); await pg.wait_for_timeout(300)
            await pg.screenshot(path=f'{SH}/v4-az-d-checkout-errors.png')
            # switch language with checkout open and errors shown
            await pg.keyboard.press('Escape'); await pg.wait_for_timeout(300)
            await pg.locator('.hdr-right [data-set-lang=\"ru\"]').click(); await pg.wait_for_timeout(500)
            print('after RU switch title:', await pg.title(), '| cart item:', await pg.evaluate("document.querySelector('#cartList .ci-name')?.textContent"))
            await pg.locator('.site-header [data-open-cart]').click(); await pg.wait_for_timeout(400)
            await pg.locator('#cartDrawer [data-checkout]').click(); await pg.wait_for_timeout(500)
            print('checkout title RU:', await pg.inner_text('#coTitle'), '| error text now:', await pg.evaluate("document.querySelector('#checkoutForm .field-error[data-err-key]')?.textContent"))
            await pg.fill('#coName', 'Leyla'); await pick_branch(pg); await pg.fill('#coPhone', '+994 050 123 45 67')
            await pg.locator('#coPhone').blur()
            await pg.locator('#checkoutForm input[name=delivery][value=courier]').check()
            await pg.fill('#coAddress', 'Nizami küç. 10, mənzil 5')
            await pg.locator('#checkoutForm input[name=payment][value=card]').check()
            await pg.fill('[name=od_sph]', '-2.00'); await pg.fill('[name=od_cyl]', '-0.50'); await pg.fill('[name=od_ax]', '180'); await pg.fill('[name=os_sph]', '-2.25'); await pg.fill('[name=pd]', '62')
            # switch to EN in the middle of filling: values must stay
            await pg.keyboard.press('Escape'); await pg.wait_for_timeout(200)
            await pg.locator('.hdr-right [data-set-lang=\"en\"]').click(); await pg.wait_for_timeout(400)
            await pg.locator('.site-header [data-open-cart]').click(); await pg.wait_for_timeout(300)
            await pg.locator('#cartDrawer [data-checkout]').click(); await pg.wait_for_timeout(500)
            print('EN checkout title:', await pg.inner_text('#coTitle'), '| name kept:', await pg.input_value('#coName'), '| phone:', await pg.input_value('#coPhone'))
            await pg.screenshot(path=f'{SH}/v4-en-d-checkout.png')
            await pg.locator('#checkoutForm [type=submit]').click(); await pg.wait_for_timeout(500)
            opened = await pg.evaluate('window.__opened')
            print('=== EN order message ==='); print(decode(opened[-1])[1])
            await pg.screenshot(path=f'{SH}/v4-en-d-success.png')
            await pg.keyboard.press('Escape'); await pg.wait_for_timeout(300)
            # back to AZ: order + repair in AZ
            await pg.locator('.hdr-right [data-set-lang=\"az\"]').click(); await pg.wait_for_timeout(400)
            await pg.locator('#catTabs [data-cat="all"]').click(); await pg.wait_for_timeout(200)
            await pg.locator('#productsGrid [data-pid="f-oslo"] [data-add]').click(); await pg.wait_for_timeout(300)
            await pg.locator('.site-header [data-open-cart]').click(); await pg.wait_for_timeout(400)
            await pg.locator('#cartDrawer [data-checkout]').click(); await pg.wait_for_timeout(500)
            await pg.screenshot(path=f'{SH}/v4-az-d-checkout.png')
            await pg.locator('#checkoutForm [type=submit]').click(); await pg.wait_for_timeout(500)
            opened = await pg.evaluate('window.__opened')
            print('=== AZ order message ==='); print(decode(opened[-1])[1])
            await pg.keyboard.press('Escape'); await pg.wait_for_timeout(300)
            # eye test button pre-selects the exam service
            await pg.locator('#eye').scroll_into_view_if_needed(); await pg.wait_for_timeout(300)
            await pg.locator('[data-pick-svc="exam"]').click(); await pg.wait_for_timeout(1200)
            print('exam checked:', await pg.is_checked('#rpServices input[data-svc-id="exam"]'))
            await pg.locator('#servicesList [data-svc="pads"]').click(); await pg.wait_for_timeout(300)
            await pg.fill('#rpDesc', 'Sol burun yastıqcığı qırılıb')
            await pg.screenshot(path=f'{SH}/v4-az-d-repair.png')
            await pg.locator('#repairForm [type=submit]').click(); await pg.wait_for_timeout(500)
            opened = await pg.evaluate('window.__opened')
            print('=== AZ repair message ==='); print(decode(opened[-1])[1])
            print('FAB link:', urllib.parse.unquote(await pg.get_attribute('.wa-float', 'href')))
            await ctx.close()
            # mobile flow in AZ
            ctx = await b.new_context(viewport={'width': 390, 'height': 844}, device_scale_factor=2, is_mobile=True, has_touch=True)
            pg = await ctx.new_page(); pg.on('pageerror', lambda e: errs.append('m:' + str(e)))
            await setup(pg)
            await pg.goto(f'{BASE}/dist/{F}'); await pg.wait_for_timeout(1500)
            await pg.locator('#productsGrid [data-pid="c-month"] [data-add]').click(); await pg.wait_for_timeout(500)
            await pg.screenshot(path=f'{SH}/v4-az-m-product.png')
            await pg.select_option('#opt-sph', '-3.00'); await pg.locator('#pmAdd').click(); await pg.wait_for_timeout(400)
            await pg.locator('.site-header [data-open-cart]').click(); await pg.wait_for_timeout(500)
            await pg.screenshot(path=f'{SH}/v4-az-m-cart.png')
            await pg.locator('#cartDrawer [data-checkout]').click(); await pg.wait_for_timeout(500)
            await pg.screenshot(path=f'{SH}/v4-az-m-checkout.png')
            await pg.keyboard.press('Escape'); await pg.wait_for_timeout(300)
            await pg.locator('.hdr-right .js-menu-toggle').click(); await pg.wait_for_timeout(300)
            await pg.screenshot(path=f'{SH}/v4-az-m-menu.png')
            await ctx.close()
        await b.close()
        print('errors:', errs or 'none')

asyncio.run(main(sys.argv[1] if len(sys.argv) > 1 else 'all'))
