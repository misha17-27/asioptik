import asyncio, sys
sys.path.insert(0, __import__('os').path.dirname(__import__('os').path.abspath(__file__)))
from run import setup, BASE, ROOT, decode
from playwright.async_api import async_playwright
F = f'{BASE}/dist/optika-4-lupa.html'
SH = f'{ROOT}/shots'

async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(executable_path='/usr/bin/google-chrome', args=['--no-sandbox'])
        errs = []
        ctx = await b.new_context(viewport={'width': 1440, 'height': 900})
        pg = await ctx.new_page()
        pg.on('pageerror', lambda e: errs.append('pageerror: ' + str(e)))
        pg.on('console', lambda m: errs.append(m.type + ': ' + m.text) if m.type == 'error' and 'Failed to load resource' not in m.text else None)
        await setup(pg)
        await pg.goto(F); await pg.wait_for_timeout(1500)
        print('nav:', await pg.evaluate("[...document.querySelectorAll('#siteNav a')].filter(a => a.offsetParent).map(a => a.textContent)"))
        print('hdr overflow px:', await pg.evaluate("document.querySelector('.hdr').scrollWidth - document.querySelector('.hdr').clientWidth"))
        print('audience sections:', await pg.evaluate("[...document.querySelectorAll('.aud')].map(s => s.id + ':' + s.querySelectorAll('.card').length)"))
        await pg.screenshot(path=f'{SH}/p4-home-full.png', full_page=True)
        # audience CTA -> catalog filtered
        await pg.locator('#kids .sb a.btn').click(); await pg.wait_for_timeout(900)
        print('kids filter:', await pg.evaluate("Shop.state.aud"), '| tabs:', await pg.evaluate("[...document.querySelectorAll('#catTabs .tab')].map(t => t.textContent.trim().replace(/\\s+/g,' '))"), '| cards:', await pg.locator('#productsGrid .card').count(), '| count text:', await pg.inner_text('#resultCount'))
        await pg.screenshot(path=f'{SH}/p4-catalog-kids.png')
        await pg.locator('[data-aud-switch] [data-key="adults"]').click(); await pg.wait_for_timeout(300)
        print('adults cards:', await pg.locator('#productsGrid .card').count())
        await pg.locator('[data-aud-switch] [data-key="women"]').click(); await pg.wait_for_timeout(300)
        print('women cards:', await pg.locator('#productsGrid .card').count())
        await pg.locator('[data-aud-switch] [data-aud=""]').click(); await pg.wait_for_timeout(300)
        print('all cards:', await pg.locator('#productsGrid .card').count())
        # product page from catalog
        y0 = await pg.evaluate('window.scrollY')
        await pg.locator('#productsGrid [data-pid="f-milan"] .card-title a').click(); await pg.wait_for_timeout(500)
        print('url:', pg.url.split('/')[-1], '| title:', await pg.title(), '| h1:', await pg.inner_text('#ppName'), '| scrollY:', await pg.evaluate('window.scrollY'), '| focus:', await pg.evaluate('document.activeElement.id'))
        print('home hidden:', await pg.evaluate("getComputedStyle(document.getElementById('catalog')).display"), '| total:', await pg.inner_text('#ppTotal'))
        await pg.screenshot(path=f'{SH}/p4-frame.png', full_page=True)
        # frame + lenses
        await pg.locator('label[for], label:has(#pp-lens-yes)').filter(has=pg.locator('#pp-lens-yes')).click(); await pg.wait_for_timeout(300)
        await pg.locator('label:has(#pp-lt-l-blue)').click(); await pg.wait_for_timeout(200)
        await pg.select_option('#pp-l-index', '1.60')
        await pg.select_option('#pp-od-sph', '-2.00'); await pg.select_option('#pp-od-cyl', '-0.50'); await pg.fill('#pp-od-ax', '180')
        await pg.select_option('#pp-os-sph', '-2.25'); await pg.select_option('#pp-pd', '62')
        print('frame+lens total:', await pg.inner_text('#ppTotal'), '|', await pg.inner_text('#ppSumNote'))
        await pg.screenshot(path=f'{SH}/p4-frame-lens.png', full_page=True)
        await pg.locator('#ppAdd').click(); await pg.wait_for_timeout(400)
        print('toast:', await pg.inner_text('#toastText'), '| count:', await pg.inner_text('.hdr-right .js-cart-count'))
        # back -> home, scroll restored
        await pg.go_back(); await pg.wait_for_timeout(500)
        print('back url:', pg.url.split('/')[-1], '| scroll restored:', y0, '->', await pg.evaluate('window.scrollY'), '| catalog display:', await pg.evaluate("getComputedStyle(document.getElementById('catalog')).display"))
        # contacts page via "Seçin"
        await pg.locator('#catTabs [data-cat="contacts"]').click(); await pg.wait_for_timeout(200)
        await pg.locator('#productsGrid [data-pid="c-daily"] [data-add]').click(); await pg.wait_for_timeout(500)
        print('contacts url:', pg.url.split('/')[-1])
        await pg.locator('#ppAdd').click(); await pg.wait_for_timeout(200)
        print('contacts errors:', (await pg.inner_text('#ppError')).replace('\n', ' / '), '| focus:', await pg.evaluate('document.activeElement.id'))
        await pg.screenshot(path=f'{SH}/p4-contacts-errors.png', full_page=True)
        await pg.select_option('#pp-od-sph', '-2.50'); await pg.select_option('#pp-os-sph', '-3.00'); await pg.select_option('#pp-p-bc', '8.5')
        await pg.locator('#pp-q-os-inc').click(); await pg.wait_for_timeout(100)
        print('contacts total:', await pg.inner_text('#ppTotal'))
        await pg.screenshot(path=f'{SH}/p4-contacts.png')
        await pg.locator('#ppAdd').click(); await pg.wait_for_timeout(300)
        # toric page direct via related? navigate by link in related
        await pg.goto(F + '?product=c-toric'); await pg.wait_for_timeout(900)
        print('direct load h1:', await pg.inner_text('#ppName'), '| lang:', await pg.evaluate('document.documentElement.lang'))
        await pg.locator('label:has(#pp-same)').click(); await pg.wait_for_timeout(200)
        await pg.screenshot(path=f'{SH}/p4-toric-same.png')
        await pg.select_option('#pp-both-sph', '-1.50'); await pg.select_option('#pp-both-cyl', '-1.25'); await pg.select_option('#pp-both-ax', '90')
        await pg.locator('#ppAdd').click(); await pg.wait_for_timeout(300)
        # progressive lens with photo
        await pg.goto(F + '?product=l-prog'); await pg.wait_for_timeout(900)
        await pg.screenshot(path=f'{SH}/p4-lens.png', full_page=True)
        await pg.locator('#ppAdd').click(); await pg.wait_for_timeout(200)
        print('prog errors:', (await pg.inner_text('#ppError')).replace('\n', ' / '))
        await pg.locator('label:has(#pp-mode-photo)').click(); await pg.wait_for_timeout(200)
        await pg.locator('#ppAdd').click(); await pg.wait_for_timeout(200)
        print('photo error:', await pg.inner_text('#ppError'))
        await pg.set_input_files('#pp-photo', f'{SH}/kit-a.png'); await pg.wait_for_timeout(300)
        await pg.screenshot(path=f'{SH}/p4-lens-photo.png')
        await pg.locator('#ppAdd').click(); await pg.wait_for_timeout(300)
        # exam mode lens
        await pg.locator('.pp-related .card-title a').first.click(); await pg.wait_for_timeout(500)
        print('related ->', await pg.inner_text('#ppName'))
        await pg.locator('label:has(#pp-mode-exam)').click(); await pg.wait_for_timeout(200)
        await pg.locator('#ppAdd').click(); await pg.wait_for_timeout(300)
        # cart + checkout
        await pg.locator('.site-header [data-open-cart]').click(); await pg.wait_for_timeout(500)
        await pg.screenshot(path=f'{SH}/p4-cart.png')
        print('cart lines:', await pg.evaluate("[...document.querySelectorAll('#cartList .ci')].map(li => li.querySelector('.ci-name').textContent + ' :: ' + [...li.querySelectorAll('.ci-opts')].map(p => p.textContent).join(' | ') + ' :: x' + li.querySelector('output').textContent)"))
        await pg.locator('#cartDrawer [data-checkout]').click(); await pg.wait_for_timeout(500)
        await pg.screenshot(path=f'{SH}/p4-checkout.png')
        await pg.fill('#coName', 'Leyla'); await pg.fill('#coPhone', '0501234567')
        await pg.locator('#checkoutForm [type=submit]').click(); await pg.wait_for_timeout(600)
        opened = await pg.evaluate('window.__opened')
        print('=== AZ message ==='); print(decode(opened[-1])[1])
        print('ok photo:', await pg.evaluate("document.getElementById('okPhoto').hidden"), '|', await pg.inner_text('#okPhotoText'), '| share btn hidden:', await pg.evaluate("document.getElementById('okShare').hidden"))
        await pg.screenshot(path=f'{SH}/p4-success.png')
        await pg.keyboard.press('Escape'); await pg.wait_for_timeout(300)
        # ссылка меню со страницы товара открывает страницу каталога «Взрослым»
        await pg.locator('#siteNav a[data-aud="adults"]').click(); await pg.wait_for_timeout(600)
        print('after nav:', pg.url.split('/')[-1], '| h1:', await pg.inner_text('#pgTitle'), '| page:', await pg.evaluate('Shop.state.page'))
        await pg.go_back(); await pg.wait_for_timeout(400)
        print('back to product:', await pg.evaluate('Shop.state.page'), '| scrollY', await pg.evaluate('window.scrollY'))
        print('errors:', errs or 'none')
        await b.close()
asyncio.run(main())
