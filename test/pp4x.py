import asyncio, sys, json
sys.path.insert(0, __import__('os').path.dirname(__import__('os').path.abspath(__file__)))
from run import setup, BASE, ROOT, decode, pick_branch
from playwright.async_api import async_playwright
F = f'{BASE}/dist/optika-4-lupa.html'
SH = f'{ROOT}/shots'
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(executable_path='/usr/bin/google-chrome', args=['--no-sandbox'])
        errs = []
        ctx = await b.new_context(viewport={'width': 1440, 'height': 900})
        pg = await ctx.new_page()
        pg.on('pageerror', lambda e: errs.append('pageerror: ' + str(e)))
        pg.on('console', lambda m: errs.append(m.type + ': ' + m.text) if m.type == 'error' and 'Failed to load resource' not in m.text else None)
        await setup(pg)
        await pg.add_init_script("navigator.canShare = d => !!(d && d.files && d.files.length); navigator.share = d => { window.__shared = d.files.map(f => f.name); return Promise.resolve(); };")
        # --- language switch keeps the configuration ---
        await pg.goto(F + '?product=f-oslo'); await pg.wait_for_timeout(1000)
        await pg.locator('label:has(#pp-p-color-1)').click()
        await pg.locator('label:has(#pp-lens-yes)').click(); await pg.wait_for_timeout(200)
        await pg.locator('label:has(#pp-lt-l-photo)').click(); await pg.wait_for_timeout(200)
        await pg.locator('label:has(#pp-l-color-1)').click()
        await pg.select_option('#pp-l-index', '1.67')
        await pg.select_option('#pp-od-sph', '+1.25'); await pg.select_option('#pp-os-sph', '+1.75'); await pg.select_option('#pp-os-cyl', '-1.00'); await pg.fill('#pp-os-ax', '15'); await pg.select_option('#pp-pd', '64')
        await pg.locator('.hdr-right [data-set-lang="ru"]').click(); await pg.wait_for_timeout(500)
        st = await pg.evaluate("JSON.stringify(Shop.state.pps['f-oslo'])")
        print('state after RU:', st)
        print('RU title:', await pg.title(), '| url:', pg.url.split('/')[-1], '| values kept:', await pg.input_value('#pp-os-ax'), await pg.input_value('#pp-od-sph'), await pg.input_value('#pp-l-index'), '| total:', await pg.inner_text('#ppTotal'), '|', await pg.inner_text('#ppSumNote'))
        await pg.screenshot(path=f'{SH}/x-ru-frame.png', full_page=True)
        # validation: CYL without AX
        await pg.fill('#pp-os-ax', '')
        await pg.locator('#ppAdd').click(); await pg.wait_for_timeout(200)
        print('RU error:', await pg.inner_text('#ppError'), '| focus:', await pg.evaluate('document.activeElement.id'))
        await pg.fill('#pp-os-ax', '200'); await pg.locator('#ppAdd').click(); await pg.wait_for_timeout(200)
        print('RU error 200:', await pg.inner_text('#ppError'))
        await pg.fill('#pp-os-ax', '15'); await pg.locator('#ppAdd').click(); await pg.wait_for_timeout(300)
        print('RU toast:', await pg.inner_text('#toastText'))
        # keyboard: arrow on mode radios keeps focus
        await pg.locator('#pp-mode-enter').focus(); await pg.keyboard.press('ArrowDown'); await pg.wait_for_timeout(200)
        print('focus after arrow:', await pg.evaluate('document.activeElement.id'), '| mode:', await pg.evaluate("Shop.state.pps['f-oslo'].mode"))
        await pg.set_input_files('#pp-photo', f'{SH}/kit-b.png'); await pg.wait_for_timeout(200)
        print('focus after photo:', await pg.evaluate('document.activeElement.id'))
        await pg.locator('#ppAdd').click(); await pg.wait_for_timeout(300)
        # EN contacts
        await pg.locator('.hdr-right [data-set-lang="en"]').click(); await pg.wait_for_timeout(300)
        await pg.goto(F + '?lang=en&product=c-color'); await pg.wait_for_timeout(900)
        await pg.screenshot(path=f'{SH}/x-en-color.png')
        print('EN cart after reload:', await pg.evaluate("JSON.stringify(Shop.state.cart.map(i => [i.id, i.qty, i.rx ? i.rx.mode : '', i.frame ? i.frame.id : '']))"))
        await pg.locator('label:has(#pp-mode-photo)').click(); await pg.wait_for_timeout(200)
        await pg.set_input_files('#pp-photo', f'{SH}/kit-a.png'); await pg.wait_for_timeout(200)
        await pg.locator('#pp-q-inc').click()
        await pg.locator('#ppAdd').click(); await pg.wait_for_timeout(300)
        await pg.locator('label:has(#pp-mode-enter)').click(); await pg.wait_for_timeout(200)
        await pg.locator('#pp-q-os-dec').click(); await pg.wait_for_timeout(200)
        print('OS off:', await pg.evaluate("document.getElementById('pp-os-sph').disabled"), '| focus kept:', await pg.evaluate('document.activeElement.id'), '| total:', await pg.inner_text('#ppTotal'))
        await pg.select_option('#pp-od-sph', '0.00'); await pg.locator('#ppAdd').click(); await pg.wait_for_timeout(300)
        await pg.locator('.site-header [data-open-cart]').click(); await pg.wait_for_timeout(400)
        await pg.screenshot(path=f'{SH}/x-en-cart.png')
        await pg.locator('#cartDrawer [data-checkout]').click(); await pg.wait_for_timeout(400)
        await pg.screenshot(path=f'{SH}/x-en-checkout.png')
        await pg.fill('#coName', 'Anna'); await pick_branch(pg); await pg.fill('#coPhone', '+994 55 111 22 33')
        await pg.locator('#checkoutForm input[name=delivery][value=courier]').check(); await pg.fill('#coAddress', '28 May St 5')
        await pg.locator('#checkoutForm [type=submit]').click(); await pg.wait_for_timeout(500)
        print('=== EN message ==='); print(decode((await pg.evaluate('window.__opened'))[-1])[1])
        print('share visible:', not await pg.evaluate("document.getElementById('okShare').hidden"), '| text:', await pg.inner_text('#okPhotoText'))
        await pg.screenshot(path=f'{SH}/x-en-success.png')
        await pg.locator('#okShare').click(); await pg.wait_for_timeout(200)
        print('shared files:', await pg.evaluate('window.__shared'))
        await pg.keyboard.press('Escape'); await pg.wait_for_timeout(200)
        # legacy cart item without rx + reload on the home page
        await pg.evaluate("localStorage.setItem('optika4-cart', JSON.stringify([{id:'l-blue', sel:{index:'1.60'}, qty:1}, {id:'c-daily', sel:{sph:'-2.50', bc:'8.5'}, qty:2}, {id:'c-daily', sel:{}, qty:1}, {id:'gone', sel:{}, qty:1}]))")
        await pg.goto(F + '?lang=en'); await pg.wait_for_timeout(800)
        print('legacy cart:', await pg.evaluate("JSON.stringify(Shop.state.cart)"))
        print('errors:', errs or 'none')
        await ctx.close()
        # --- file:// : pages must work when the file is opened from disk ---
        ctx = await b.new_context(viewport={'width': 1280, 'height': 800})
        pg = await ctx.new_page(); ferr = []
        pg.on('pageerror', lambda e: ferr.append(str(e)))
        await pg.route('https://**', lambda r: r.abort())
        url = 'file://' + __import__('os').path.dirname(__import__('os').path.dirname(__import__('os').path.abspath(__file__))) + '/dist/optika-4-lupa.html'
        await pg.goto(url + '?page=catalog'); await pg.wait_for_timeout(800)
        await pg.locator('#productsGrid [data-pid="f-verona"] .card-title a').click(); await pg.wait_for_timeout(500)
        print('file url:', pg.url.split('/')[-1], '| page:', await pg.evaluate('Shop.state.page'), '| h1:', await pg.inner_text('#ppName'))
        await pg.locator('#ppAdd').click(); await pg.wait_for_timeout(300)
        await pg.reload(); await pg.wait_for_timeout(700)
        print('file reload page:', await pg.evaluate('Shop.state.page'), '| cart:', await pg.evaluate('Shop.state.cart.length'))
        await pg.go_back(); await pg.wait_for_timeout(500)
        print('file back:', pg.url.split('/')[-1], '| page:', repr(await pg.evaluate('Shop.state.page')))
        await pg.locator('.hdr-right [data-set-lang="ru"]').click(); await pg.wait_for_timeout(300)
        print('file lang url:', pg.url.split('/')[-1], '| card href:', await pg.get_attribute('#productsGrid [data-pid="f-milan"] .card-title a', 'href'))
        print('file errors:', ferr or 'none')
        await b.close()
asyncio.run(main())
