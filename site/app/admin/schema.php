/* Описание того, что редактируется в админ-панели: какие поля есть у товара, раздела, бренда, статьи и так далее. */
declare(strict_types=1);

function opt_categories(): array
{
    $o = [];
    foreach (items('category') as $c) $o[$c['slug']] = tr_admin($c['data']['name'] ?? $c['slug']);
    return $o;
}

function opt_brands(): array
{
    $o = [];
    foreach (items('brand') as $b) $o[$b['slug']] = (string) ($b['data']['name'] ?? $b['slug']);
    return $o;
}

function opt_products(): array
{
    $o = [];
    foreach (items('product') as $p) $o[$p['slug']] = tr_admin($p['data']['name'] ?? $p['slug']);
    return $o;
}

/** Куда может вести кнопка в конце статьи. */
function opt_post_links(): array
{
    $o = ['catalog:all' => __('Каталог: все товары'), 'catalog:all:kids' => __('Каталог: детские модели')];
    foreach (opt_categories() as $id => $name) $o['catalog:' . $id] = __('Каталог: {name}', ['name' => $name]);
    $o['repair'] = __('Мастерская (заявка на ремонт)');
    return $o;
}

/** Текст для списков админ-панели: на языке интерфейса, а если такого перевода нет — на основном языке сайта, затем на остальных. */
function tr_admin($v): string
{
    if (!is_array($v)) return (string) $v;
    foreach (array_unique([ui_lang(), 'az', 'ru', 'en']) as $l) {
        if (isset($v[$l]) && is_scalar($v[$l]) && (string) $v[$l] !== '') return (string) $v[$l];
    }
    return '';
}

